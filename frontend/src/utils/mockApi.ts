const ABSOLUTE_WORDS = ['绝了', 'yyds', '太香了', '最好', '第一', '绝对', '完美', '超级', '完全', '必须', '一定', '保证', '承诺', '效果翻倍', '按头安利'];

const SENSITIVE_WORDS = ['医美', '整容', '整形', '减肥', '瘦身', '丰胸', '美白针', '玻尿酸', '肉毒素', '减肥药', '瘦身药', '保健品', '保健食品', '医疗器械', '医疗建议', '治疗', '治愈', '药效', '疗效', '功效', '神效', '奇效', '速效'];

const BANNED_BRANDS = ['医度森', '宫芙'];

const checkCompliance = (text: string): { isCompliant: boolean; warnings: string[] } => {
  const warnings: string[] = [];
  
  for (const word of ABSOLUTE_WORDS) {
    if (text.includes(word)) {
      warnings.push(`包含绝对化用语"${word}"，建议使用相对化表达`);
    }
  }
  
  for (const word of SENSITIVE_WORDS) {
    if (text.includes(word)) {
      warnings.push(`包含敏感词"${word}"，可能涉及医疗保健内容`);
    }
  }
  
  for (const brand of BANNED_BRANDS) {
    if (text.includes(brand)) {
      warnings.push(`包含违规品牌"${brand}"，已被平台封禁`);
    }
  }
  
  return {
    isCompliant: warnings.length === 0,
    warnings,
  };
};

const sanitizeContent = (text: string): string => {
  let sanitized = text;
  
  const replacements: Record<string, string> = {
    '绝了': '挺不错的',
    'yyds': '还不错',
    '太香了': '挺喜欢的',
    '最好': '不错的',
    '第一': '不错的',
    '绝对': '比较',
    '完美': '挺好的',
    '超级': '挺',
    '完全': '挺',
    '必须': '建议',
    '一定': '可能',
    '保证': '可能会',
    '承诺': '可能会',
    '效果翻倍': '效果可能会更好',
    '按头安利': '推荐',
  };
  
  for (const [word, replacement] of Object.entries(replacements)) {
    sanitized = sanitized.replace(new RegExp(word, 'g'), replacement);
  }
  
  return sanitized;
};

